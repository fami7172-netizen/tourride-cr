export function makeT(lang) {
  const s = strings[lang] || strings.es;
  return (key, vars) => {
    let out = s[key] ?? strings.es[key] ?? key;
    if (vars) for (const k in vars) out = out.replace('{' + k + '}', vars[k]);
    return out;
  };
}
